// Using Constants
class Sixth {
    public static void main(String[] args) {
        final int MAX_AGE = 100;          // constant integer
        final double PI = 3.14159;       // constant decimal
        final char GRADE_A = 'A';        // constant character
        final boolean IS_ACTIVE = true;  // constant boolean

        System.out.println("Max Age: " + MAX_AGE);
        System.out.println("PI: " + PI);
        System.out.println("Grade A: " + GRADE_A);
        System.out.println("Is Active: " + IS_ACTIVE);
    }
}
